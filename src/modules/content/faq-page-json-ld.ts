export interface FaqPageItem {
  question: string;
  answer: string;
}

export function buildFaqPageJsonLd(items: readonly FaqPageItem[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: items.map((item) => ({
      "@type": "Question",
      name: item.question,
      acceptedAnswer: {
        "@type": "Answer",
        text: item.answer,
      },
    })),
  } as const;
}
